function makePostTask05UnifiedScenario(params: {
  id: RuleScenarioId;
  labelZh: string;
  labelEn: string;
  descriptionZh: string;
  platformBase: 'web' | 'ios' | 'unified';
}): RuleScenarioSpec {
  const world = worldAndProgressionJson;
  const eco = economyPredationJson;
  const preyEco = preyEcologyJson;
  const crown = crownMasteryJson;
  const ads = adsConfigJson.placements;

  return {
    id: params.id,
    labelZh: params.labelZh,
    labelEn: params.labelEn,
    descriptionZh: params.descriptionZh,
    platformBase: params.platformBase,
    initialCoins: world.starterSaveDefaults.bankedCoins,
    initialGenes: world.starterSaveDefaults.bankedGenes,
    initialBestDepth: world.starterSaveDefaults.bestDepthReached,
    geneBreakthroughMinRef: world.upgradeProgression.geneUnlockMinRef,
    allowVerticalParentUnlock: world.upgradeProgression.allowVerticalParentUnlock,
    crownsUseIosTable: false,
    crownsTiming: crown.settlementTiming as 'end_of_run',
    crownCoinScale: 1,
    crownGeneScale: 1,
    predationMode: 'web_post_p0_single_pickup',
    mutationMode: 'unified_balanced',
    goldenNeedForFrenzy: eco.frenzy.goldenChargeRequired,
    frenzyCooldownSec: eco.frenzy.cooldownSec,
    frenzyInitProtectionSec: eco.frenzy.initProtectionSec,
    frenzyBaseDurationSec: eco.frenzy.baseDurationSec,
    frenzyRewardMult: eco.frenzy.coinMultiplier,
    armorCrushHitsNeeded: eco.armorCrush.bossOrBehemothHitsRequired,
    armorCrushBypassesMultAndBounty: false,
    pickupLifetimeSec: eco.pickups.lifetimeSec,
    frenzyPickupMagnetBonusFlat: 0,
    collectRadiusWorldFactor: eco.pickups.collectRadiusWorldFactor,
    maxActivePreys: preyEco.spawnerRules.maxActivePreys,
    allowDepthHazardsInPool: false,
    normalXpScale: eco.xpMultipliers.normal,
    frenzyXpScale: eco.xpMultipliers.frenzy,
    armorCrushXpScale: eco.xpMultipliers.armorCrush,
    goldenXpScale: eco.xpMultipliers.golden,
    bountyMode: 'unified_scaled_2kill',
    difficultyPer60s: world.timeDifficulty.ratePerInterval,
    useSharkSpecificYieldTraits: true,
    heatMode: 'web_score_magnet_regen',
    goldOverdriveBlockWhileFrenzy: eco.activeSkills.goldOverdrive.blockWhileFrenzy,
    goldOverdriveDurationBase: eco.activeSkills.goldOverdrive.durationSec,
    goldOverdriveHealPctOrFlat: {
      kind: 'pct',
      value: eco.activeSkills.goldOverdrive.healMaxHpPct,
    },
    isolateTrialProgress: true,
    adCapabilities: {
      hasSupplyDrop: ads.SUPPLY_DROP.enabled,
      supplyDropCoins: ads.SUPPLY_DROP.rewardsByMaxUnlockedRow[0].coins,
      supplyDropGenes: ads.SUPPLY_DROP.rewardsByMaxUnlockedRow[0].genes,
      useRowScaledSupplyDrop: true,
      supplyDropCapPerDay: ads.SUPPLY_DROP.dailyCap,
      hasDoubleSettlement: ads.DOUBLE_SETTLEMENT.enabled,
      doubleSettlementCapPerDay: ads.DOUBLE_SETTLEMENT.dailyCap,
      doubleSettlementFloorCoins: ads.DOUBLE_SETTLEMENT.minNetPositiveFloor,
      doubleSettlementFloorGenes: ads.DOUBLE_SETTLEMENT.minNetPositiveFloor,
      reviveCapPerDay: ads.REVIVE.dailyCap,
      trialCapPerDay: ads.TRIAL_SHARK.dailyCap,
    },
  };
}

